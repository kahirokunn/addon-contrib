func writePolicyRulesFunc(b *strings.Builder, name string, rules []rbacv1.PolicyRule) {
	fmt.Fprintf(b, "func %s() []rbacv1.PolicyRule {\n", name)
	b.WriteString("\treturn []rbacv1.PolicyRule{\n")
	for _, rule := range rules {
		b.WriteString("\t\t{")
		fmt.Fprintf(b, "APIGroups: []string{%s}, ", quotedStrings(rule.APIGroups))
		fmt.Fprintf(b, "Resources: []string{%s}, ", quotedStrings(rule.Resources))
		fmt.Fprintf(b, "Verbs: []string{%s}", quotedStrings(rule.Verbs))
		if len(rule.ResourceNames) > 0 {
			fmt.Fprintf(b, ", ResourceNames: []string{%s}", quotedStrings(rule.ResourceNames))
		}
		if len(rule.NonResourceURLs) > 0 {
			fmt.Fprintf(b, ", NonResourceURLs: []string{%s}", quotedStrings(rule.NonResourceURLs))
		}
		b.WriteString("},\n")
	}
	b.WriteString("\t}\n")
	b.WriteString("}\n\n")
}

func quotedStrings(values []string) string {
	out := make([]string, 0, len(values))
	for _, value := range values {
		out = append(out, strconv.Quote(value))
	}
	return strings.Join(out, ", ")
}

func mapAt(root map[string]interface{}, path ...string) (map[string]interface{}, error) {
	current := root
	for _, field := range path {
		next, ok := current[field].(map[string]interface{})
		if !ok {
			return nil, fmt.Errorf("field %s is not an object", strings.Join(path, "."))
		}
		current = next
	}
	return current, nil
}

func sliceAt(root map[string]interface{}, path ...string) ([]interface{}, error) {
	if len(path) == 0 {
		return nil, errors.New("slice path is empty")
	}
	parent, err := mapAt(root, path[:len(path)-1]...)
	if err != nil {
		return nil, err
	}
	value, ok := parent[path[len(path)-1]].([]interface{})
	if !ok {
		return nil, fmt.Errorf("field %s is not a list", strings.Join(path, "."))
	}
	return value, nil
}

func marshalGeneratedYAML(value interface{}) (string, error) {
	var buf bytes.Buffer
	buf.WriteString(generatedComment)
	encoder := yamlv3.NewEncoder(&buf)
	encoder.SetIndent(yamlNestIndent)
	if err := encoder.Encode(value); err != nil {
		return "", err
	}
	if err := encoder.Close(); err != nil {
		return "", err
	}
	out := strings.TrimSuffix(buf.String(), "...\n")
	if !strings.HasSuffix(out, "\n") {
		out += "\n"
	}
	return applySentinels(out), nil
}

func writeFile(repoRoot, path, content string) error {
	fullPath := filepath.Join(repoRoot, path)
	if err := os.MkdirAll(filepath.Dir(fullPath), 0o755); err != nil {
		return err
	}
	return os.WriteFile(fullPath, []byte(content), 0o644)
}

func envOrDefault(key, defaultValue string) string {
	if value := strings.TrimSpace(os.Getenv(key)); value != "" {
		return value
	}
	return defaultValue
}
